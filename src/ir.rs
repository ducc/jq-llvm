//! A tiny textual LLVM IR builder. Values are plain strings ("%t12", "0",
//! "@foo"); types are strings too ("i64", "ptr", "%V"). Everything the
//! compiler emits — the jq runtime and the compiled filter — goes through
//! this module.

use std::collections::{BTreeMap, HashMap};
use std::fmt::Write;

pub const V: &str = "%V";

#[derive(Default)]
pub struct Module {
    pub globals: Vec<String>,
    pub funcs: Vec<String>,
    pub decls: BTreeMap<String, String>,
    strs: HashMap<Vec<u8>, String>,
}

impl Module {
    pub fn new() -> Self {
        Self::default()
    }

    /// NUL-terminated private string constant; returns the global (a ptr).
    pub fn cstr(&mut self, s: impl AsRef<[u8]>) -> String {
        let s = s.as_ref();
        if let Some(g) = self.strs.get(s) {
            return g.clone();
        }
        let name = format!("@.str.{}", self.strs.len());
        self.globals.push(format!(
            "{} = private unnamed_addr constant [{} x i8] c\"{}\", align 1",
            name,
            s.len() + 1,
            escape_bytes(s, true)
        ));
        self.strs.insert(s.to_vec(), name.clone());
        name
    }

    pub fn global(&mut self, text: String) {
        self.globals.push(text);
    }

    /// Declare an external (libc) function, e.g. declare("malloc", "declare ptr @malloc(i64)").
    pub fn declare(&mut self, name: &str, decl: &str) {
        self.decls.entry(name.to_string()).or_insert_with(|| decl.to_string());
    }

    pub fn add(&mut self, f: Func) {
        self.funcs.push(f.finish());
    }

    pub fn render(&self, types: &str) -> String {
        let mut out = String::new();
        out.push_str("; generated by jqc\n");
        out.push_str("%V = type { i64, i64 }\n");
        out.push_str(types);
        out.push('\n');
        for d in self.decls.values() {
            out.push_str(d);
            out.push('\n');
        }
        out.push('\n');
        for g in &self.globals {
            out.push_str(g);
            out.push('\n');
        }
        out.push('\n');
        for f in &self.funcs {
            out.push_str(f);
            out.push('\n');
        }
        out
    }
}

pub fn escape_bytes(s: &[u8], nul: bool) -> String {
    let mut o = String::new();
    for &b in s {
        if b.is_ascii_graphic() && b != b'"' && b != b'\\' || b == b' ' {
            o.push(b as char);
        } else {
            let _ = write!(o, "\\{:02X}", b);
        }
    }
    if nul {
        o.push_str("\\00");
    }
    o
}

pub fn fconst(x: f64) -> String {
    // LLVM accepts hex bit patterns for doubles: always exact.
    format!("0x{:016X}", x.to_bits())
}

pub struct Func {
    header: String,
    allocas: Vec<String>,
    body: Vec<String>,
    n: usize,
    labels: usize,
    pub terminated: bool,
    name: String,
}

impl Func {
    /// `attrs` go after the parameter list (e.g. "alwaysinline").
    pub fn new(linkage: &str, ret: &str, name: &str, params: &[(&str, &str)], attrs: &str) -> Func {
        let ps: Vec<String> = params.iter().map(|(t, n)| format!("{} %{}", t, n)).collect();
        Func {
            name: name.to_string(),
            header: format!(
                "define {} {} @{}({}) {} {{",
                linkage,
                ret,
                name,
                ps.join(", "),
                attrs
            ),
            allocas: vec![],
            body: vec![],
            n: 0,
            labels: 0,
            terminated: false,
        }
    }

    pub fn finish(self) -> String {
        let mut s = self.header;
        s.push_str("\n__entry:\n");
        for a in &self.allocas {
            s.push_str("  ");
            s.push_str(a);
            s.push('\n');
        }
        s.push_str("  br label %__start\n__start:\n");
        for l in &self.body {
            if l.ends_with(':') {
                s.push_str(l);
            } else {
                s.push_str("  ");
                s.push_str(l);
            }
            s.push('\n');
        }
        if !self.terminated {
            s.push_str("  unreachable\n");
        }
        s.push_str("}\n");
        s
    }

    pub fn tmp(&mut self) -> String {
        self.n += 1;
        format!("%t{}", self.n)
    }

    pub fn label(&mut self, hint: &str) -> String {
        self.labels += 1;
        format!("{}_{}", hint, self.labels)
    }

    /// Emit an instruction producing a value.
    pub fn ins(&mut self, s: impl AsRef<str>) -> String {
        let t = self.tmp();
        if self.terminated {
            if std::env::var("JQC_STRICT").is_ok() {
                panic!("value after terminator in {}: {}", self.name, s.as_ref());
            }
            // Dead code after a terminator: give it a fresh block so IR stays valid.
            let l = self.label("dead");
            self.block(&l);
        }
        self.body.push(format!("{} = {}", t, s.as_ref()));
        t
    }

    /// Emit an instruction with no result.
    pub fn op(&mut self, s: impl AsRef<str>) {
        if self.terminated {
            let l = self.label("dead");
            self.block(&l);
        }
        self.body.push(s.as_ref().to_string());
    }

    pub fn block(&mut self, l: &str) {
        if !self.terminated {
            self.body.push(format!("br label %{}", l));
        }
        self.body.push(format!("{}:", l));
        self.terminated = false;
    }

    pub fn br(&mut self, l: &str) {
        if !self.terminated {
            self.body.push(format!("br label %{}", l));
            self.terminated = true;
        }
    }

    pub fn cbr(&mut self, c: &str, a: &str, b: &str) {
        self.op(format!("br i1 {}, label %{}, label %{}", c, a, b));
        self.terminated = true;
    }

    pub fn ret(&mut self, ty: &str, v: &str) {
        self.op(format!("ret {} {}", ty, v));
        self.terminated = true;
    }

    pub fn ret_void(&mut self) {
        self.op("ret void");
        self.terminated = true;
    }

    pub fn unreachable(&mut self) {
        self.op("unreachable");
        self.terminated = true;
    }

    pub fn push_alloca(&mut self, line: String) {
        self.allocas.push(line);
    }

    pub fn var(&mut self, ty: &str) -> String {
        self.n += 1;
        let name = format!("%v{}", self.n);
        self.allocas.push(format!("{} = alloca {}", name, ty));
        name
    }

    pub fn var_init(&mut self, ty: &str, init: &str) -> String {
        let p = self.var(ty);
        self.store(ty, init, &p);
        p
    }

    pub fn array_var(&mut self, ty: &str, n: usize) -> String {
        self.n += 1;
        let name = format!("%v{}", self.n);
        self.allocas.push(format!("{} = alloca {}, i64 {}", name, ty, n));
        name
    }

    pub fn load(&mut self, ty: &str, p: &str) -> String {
        self.ins(format!("load {}, ptr {}", ty, p))
    }

    pub fn store(&mut self, ty: &str, v: &str, p: &str) {
        self.op(format!("store {} {}, ptr {}", ty, v, p));
    }

    /// Byte-offset pointer arithmetic.
    pub fn off(&mut self, p: &str, off: &str) -> String {
        self.ins(format!("getelementptr inbounds i8, ptr {}, i64 {}", p, off))
    }

    pub fn ld_at(&mut self, ty: &str, p: &str, off: i64) -> String {
        let q = if off == 0 { p.to_string() } else { self.off(p, &off.to_string()) };
        self.load(ty, &q)
    }

    pub fn st_at(&mut self, ty: &str, v: &str, p: &str, off: i64) {
        let q = if off == 0 { p.to_string() } else { self.off(p, &off.to_string()) };
        self.store(ty, v, &q);
    }

    /// Element pointer: p + i*size
    pub fn idx(&mut self, p: &str, i: &str, size: i64) -> String {
        let o = self.bin("mul", "i64", i, &size.to_string());
        self.off(p, &o)
    }

    pub fn bin(&mut self, op: &str, ty: &str, a: &str, b: &str) -> String {
        self.ins(format!("{} {} {}, {}", op, ty, a, b))
    }

    pub fn add(&mut self, a: &str, b: &str) -> String {
        self.bin("add", "i64", a, b)
    }
    pub fn sub(&mut self, a: &str, b: &str) -> String {
        self.bin("sub", "i64", a, b)
    }

    pub fn icmp(&mut self, pred: &str, ty: &str, a: &str, b: &str) -> String {
        self.ins(format!("icmp {} {} {}, {}", pred, ty, a, b))
    }
    pub fn eq(&mut self, a: &str, b: &str) -> String {
        self.icmp("eq", "i64", a, b)
    }
    pub fn ne(&mut self, a: &str, b: &str) -> String {
        self.icmp("ne", "i64", a, b)
    }
    pub fn lt(&mut self, a: &str, b: &str) -> String {
        self.icmp("slt", "i64", a, b)
    }

    pub fn fcmp(&mut self, pred: &str, a: &str, b: &str) -> String {
        self.ins(format!("fcmp {} double {}, {}", pred, a, b))
    }

    pub fn and1(&mut self, a: &str, b: &str) -> String {
        self.bin("and", "i1", a, b)
    }
    pub fn or1(&mut self, a: &str, b: &str) -> String {
        self.bin("or", "i1", a, b)
    }
    pub fn not1(&mut self, a: &str) -> String {
        self.bin("xor", "i1", a, "true")
    }

    pub fn select(&mut self, c: &str, ty: &str, a: &str, b: &str) -> String {
        self.ins(format!("select i1 {}, {} {}, {} {}", c, ty, a, ty, b))
    }

    pub fn cast(&mut self, op: &str, from: &str, v: &str, to: &str) -> String {
        self.ins(format!("{} {} {} to {}", op, from, v, to))
    }

    pub fn call(&mut self, ret: &str, f: &str, args: &[(&str, &str)]) -> String {
        let a: Vec<String> = args.iter().map(|(t, v)| format!("{} {}", t, v)).collect();
        let fname = if f.starts_with('@') || f.starts_with('%') {
            f.to_string()
        } else {
            format!("@{}", f)
        };
        if ret == "void" {
            self.op(format!("call void {}({})", fname, a.join(", ")));
            String::new()
        } else {
            self.ins(format!("call {} {}({})", ret, fname, a.join(", ")))
        }
    }

    // ---- %V helpers ----
    pub fn mkv(&mut self, tag: &str, bits: &str) -> String {
        let a = self.ins(format!("insertvalue %V undef, i64 {}, 0", tag));
        self.ins(format!("insertvalue %V {}, i64 {}, 1", a, bits))
    }
    /// Kind tag (low byte). The upper bits of a number's tag word may carry a
    /// pointer to its preserved literal text (see rt::json).
    pub fn tag(&mut self, v: &str) -> String {
        let raw = self.rawtag(v);
        self.ins(format!("and i64 {}, 255", raw))
    }
    pub fn rawtag(&mut self, v: &str) -> String {
        self.ins(format!("extractvalue %V {}, 0", v))
    }
    pub fn bits(&mut self, v: &str) -> String {
        self.ins(format!("extractvalue %V {}, 1", v))
    }
    pub fn ptr_of(&mut self, v: &str) -> String {
        let b = self.bits(v);
        self.cast("inttoptr", "i64", &b, "ptr")
    }
    pub fn num_of(&mut self, v: &str) -> String {
        let b = self.bits(v);
        self.cast("bitcast", "i64", &b, "double")
    }
    pub fn mknum(&mut self, d: &str) -> String {
        let b = self.cast("bitcast", "double", d, "i64");
        self.mkv("3", &b)
    }
    pub fn mkptr(&mut self, tag: &str, p: &str) -> String {
        let b = self.cast("ptrtoint", "ptr", p, "i64");
        self.mkv(tag, &b)
    }
    pub fn tag_is(&mut self, v: &str, tag: i64) -> String {
        let t = self.tag(v);
        self.eq(&t, &tag.to_string())
    }

    // ---- structured control flow ----
    pub fn if_then<R>(&mut self, c: &str, then: impl FnOnce(&mut Func) -> R) {
        let lt = self.label("then");
        let le = self.label("endif");
        self.cbr(c, &lt, &le);
        self.block(&lt);
        then(self);
        self.br(&le);
        self.block(&le);
    }

    pub fn if_else<R1, R2>(&mut self, c: &str, then: impl FnOnce(&mut Func) -> R1, els: impl FnOnce(&mut Func) -> R2) {
        let lt = self.label("then");
        let lf = self.label("else");
        let le = self.label("endif");
        self.cbr(c, &lt, &lf);
        self.block(&lt);
        then(self);
        self.br(&le);
        self.block(&lf);
        els(self);
        self.br(&le);
        self.block(&le);
    }

    /// if/else producing a value of type `ty`.
    pub fn if_val(
        &mut self,
        c: &str,
        ty: &str,
        then: impl FnOnce(&mut Func) -> String,
        els: impl FnOnce(&mut Func) -> String,
    ) -> String {
        let r = self.var(ty);
        let ty2 = ty.to_string();
        let r2 = r.clone();
        self.if_else(
            c,
            |f| {
                let v = then(f);
                if !f.terminated {
                    f.store(&ty2, &v, &r2);
                }
            },
            |f| {
                let v = els(f);
                if !f.terminated {
                    f.store(&ty2, &v, &r2);
                }
            },
        );
        self.load(ty, &r)
    }

    /// Loop: `cond` computes an i1 at the top of each iteration; body runs while true.
    /// Body receives (break_label, continue_label).
    pub fn while_(&mut self, cond: impl FnOnce(&mut Func) -> String, body: impl FnOnce(&mut Func, &str, &str)) {
        let lh = self.label("loop");
        let lb = self.label("body");
        let le = self.label("endloop");
        self.br(&lh);
        self.block(&lh);
        let c = cond(self);
        self.cbr(&c, &lb, &le);
        self.block(&lb);
        body(self, &le, &lh);
        self.br(&lh);
        self.block(&le);
    }

    /// for i in [from, to): body(f, i, break, continue)
    pub fn for_range(&mut self, from: &str, to: &str, body: impl FnOnce(&mut Func, &str, &str, &str)) {
        let iv = self.var_init("i64", from);
        let lh = self.label("for");
        let lb = self.label("forbody");
        let lc = self.label("forcont");
        let le = self.label("endfor");
        self.br(&lh);
        self.block(&lh);
        let i = self.load("i64", &iv);
        let c = self.lt(&i, to);
        self.cbr(&c, &lb, &le);
        self.block(&lb);
        body(self, &i, &le, &lc);
        self.br(&lc);
        self.block(&lc);
        let i2 = self.load("i64", &iv);
        let n = self.add(&i2, "1");
        self.store("i64", &n, &iv);
        self.br(&lh);
        self.block(&le);
    }

    /// Multi-way switch on an i64. `cases` is a list of (value, label); returns nothing,
    /// caller emits the blocks.
    pub fn switch(&mut self, v: &str, default: &str, cases: &[(i64, String)]) {
        let mut s = format!("switch i64 {}, label %{} [", v, default);
        for (c, l) in cases {
            let _ = write!(s, " i64 {}, label %{}", c, l);
        }
        s.push_str(" ]");
        self.op(s);
        self.terminated = true;
    }
}

impl Func {
    pub fn name(&self) -> &str {
        &self.name
    }
}
